/**
 * 진료과목 데이터.
 *
 * ★ 왜 데이터로 두는가 — 페이지를 손으로 하나씩 쓰면 20개째부터 구조가 어긋난다.
 *   JSON-LD(MedicalProcedure), 사이트맵, 내부 링크, 목차가 전부 이 배열에서 파생되므로
 *   항목을 추가하면 페이지·구조화 데이터·사이트맵이 동시에 따라온다(drift 0).
 *
 * ★ AEO 를 노린 문서 구조 — `qa` 배열이 핵심이다.
 *   AI 검색엔진은 "질문 + 그 자리에서 끝나는 짧은 답"을 인용한다. 그래서 각 항목은
 *   ① 환자가 실제로 치는 자연어 질문을 그대로 제목으로 쓰고,
 *   ② `answer` 첫 2~3문장 안에서 답을 끝내고,
 *   ③ 배경 설명은 그 뒤에 잇는다.
 *   답을 세 문단 뒤에 숨기면 인용되지 않는다.
 *
 * ⚠️ 의료광고법 — 효과를 단정하거나 최상급을 쓰지 않는다.
 *   "완치", "무통", "100%", "최고", "국내 유일" 금지. 부작용 가능성은 숨기지 않는다.
 */

export interface TreatmentQA {
  /** 환자가 실제로 검색창에 치는 문장 그대로. */
  q: string;
  /** 첫 2~3문장에서 답이 끝나야 한다. 뒤에 배경을 잇는다. */
  a: string;
}

export interface Treatment {
  slug: string;
  /** 페이지 제목에 쓰는 정식 명칭. */
  name: string;
  /** 메뉴·칩에 쓰는 짧은 이름. */
  short: string;
  /** 한 줄 요약 — 메타 설명과 카드에 함께 쓴다. */
  summary: string;
  /** 이 진료를 찾는 대표적인 상황. 검색 의도와 맞춘다. */
  whoFor: string[];
  /** 본문 도입 — 흐르는 글 한 문단. */
  intro: string;
  qa: TreatmentQA[];
  /** 연결되는 증상 slug — 내부 링크 그래프를 만든다. */
  relatedSymptoms: string[];
  /** 이 진료에 해당하는 국제 표준 분류(JSON-LD MedicalProcedure.procedureType 힌트). */
  procedureType: 'SurgicalProcedure' | 'TherapeuticProcedure' | 'DiagnosticProcedure' | 'PreventiveProcedure';
  /**
   * 구조·과정 설명용 이미지. **선택**이다 — 없으면 섹션 자체가 렌더되지 않는다.
   *
   * ★★ 이것은 '우리 병원 장비 사진' 이 아니다 ★★
   *   AI 로 만든 설명용 이미지다. 실제 진료 사진처럼 보이게 두면 그 순간
   *   "이 병원이 이 장비를 갖췄다" 는 확인되지 않은 주장이 된다(의료법 제56조).
   *   그래서 ① 병원 공간·유닛체어를 재현하지 않고 ② 제조사 각인을 넣지 않으며
   *   ③ 섹션 하단에 설명용이라는 고지를 함께 렌더한다. 셋 다 지울 수 없는 조건이다.
   * ⚠️ 실제 원내 장비 사진을 확보하면 이 배열을 그 사진으로 교체하고 고지를 뺀다.
   *   그때가 이 자리의 값이 '설명' 에서 '증거' 로 바뀌는 지점이다.
   */
  figures?: Array<{ src: string; alt: string; caption: string }>;
  /** figures 섹션의 h2. 그 그림들이 실제로 답하는 질문을 적는다(목차·답변 엔진이 읽는 자리). */
  figuresTitle?: string;
}

