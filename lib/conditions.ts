/**
 * 질환 사전 — 치과 질환을 이름으로 찾는 축.
 *
 * ★ 증상 축과 직교한다
 *   증상 축("이가 시려요")은 병명을 모르는 사람이 들어오는 입구고,
 *   여기는 **이미 병명을 들은 사람**이 들어오는 입구다.
 *   진료실에서 "치주염입니다" 라는 말을 듣고 나온 환자가 그날 저녁에 검색하는 것이 이쪽이며,
 *   AI 에게도 "치주염이 뭐예요" "드라이소켓 얼마나 가요" 형태로 그대로 들어온다.
 *
 * ★ 문서 구조 — 정의가 맨 앞이다
 *   `definition` 은 한 문장으로 끝낸다. AI 는 정의형 질의에 대해 **첫 문장을 그대로 인용**한다.
 *   길게 풀면 인용 대상에서 밀리고, 두 문장으로 나누면 뒤 문장이 잘린다.
 *
 * ★★ 여기 있는 내용은 전부 일반적인 치과 의학 정보다 ★★
 *   특정 병원의 실적·방침·비용을 주장하지 않는다. 그래야 사실 확인이 필요 없고,
 *   병원 사정이 바뀌어도 이 문서들은 그대로 유효하다.
 */

export interface Condition {
  slug: string;
  /** 정식 병명. */
  name: string;
  /** 환자가 흔히 쓰는 다른 이름. 검색 질의와 매칭된다. */
  aka: string[];
  /** ★ 한 문장 정의. AI 인용 대상 — 반드시 한 문장으로 끝낸다. */
  definition: string;
  /** 정의를 잇는 배경 설명(흐르는 글 한 문단). */
  detail: string;
  /** 이 질환에서 나타나는 증상. */
  signs: string[];
  /** 원인·위험 요인. */
  causes: string[];
  /** 방치했을 때의 진행 단계. '언제 가야 하나'를 스스로 판단하게 해 준다. */
  stages: Array<{ step: string; what: string }>;
  /** 일반적인 치료 방향. 특정 병원의 방침이 아니라 표준 치료다. */
  treatment: string;
  /** 예방·관리. */
  prevention: string[];
  /** 자주 묻는 것. FAQPage 스키마로 나간다. */
  faq: Array<{ q: string; a: string }>;
  /** 연결 — 내부 링크 그래프. */
  relatedSymptoms: string[];
  relatedTreatments: string[];
}

