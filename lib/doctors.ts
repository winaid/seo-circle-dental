/**
 * ⚠️⚠️ **메인에 내보내는 요약은 원문의 부분집합이어야 한다** ⚠️⚠️
 *   license 와 keyCareer 는 career 에서 **고른 것**이지 새로 쓴 것이 아니다.
 *   요약하다 한 글자라도 바뀌면 그것은 의료인 경력의 허위 표시가 된다(의료법 제56조).
 *   여기서 즉시 던진다 — 화면에 조용히 잘못 나가는 것보다 빌드가 깨지는 편이 낫다.
 */
for (const d of DOCTORS) {
  for (const line of [d.license, ...d.keyCareer]) {
    if (!d.career.includes(line)) {
      throw new Error(`[doctors] ${d.name}: '${line}' 은 career 원문에 없다 — 요약하지 말고 원문에서 고를 것`);
    }
  }
}

/**
 * 메인 카드에 실을 **자격 근거** — 학회 또는 수료 과정.
 *
 * ★★ 왜 focus(진료분야) 를 안 쓰는가 (2026-08-31 운영자 확인) ★★
 *   운영자: "진료분야가 실제 동그라미치과 기준 맞지? 추론 아니고?" — **추론이었다.**
 *   focus 는 병원이 공표한 진료과목이 아니라 학회·수료 목록에서 역산한 값이다.
 *   실제로 김동주 원장의 '근관치료' 는 학회 넷 어디에도 없고(수료 과정에서 왔다),
 *   김인진 원장은 학회가 0개인데 네 항목이 붙어 있었으며 'UCLA 교정과정 수료' 가
 *   있는데도 '교정' 은 빠져 있었다 — 고르는 기준 자체가 일관되지 않았다.
 *   의료인의 진료과목 표시는 사실과 달라선 안 된다(의료법 제56조).
 * ★ 그래서 화면에는 **원문 그대로**를 싣는다. 학회가 있으면 학회, 없으면 수료 과정.
 *   요약하거나 단어로 바꾸지 않으므로 확인 없이도 사실이다.
 *
 * ⚠️ focus 는 지우지 않았다 — 상세 페이지와 Physician 스키마의 knowsAbout 이 쓴다.
 *    그쪽까지 정리하려면 SEO 영향이 있어 운영자 판단이 필요하다.
 */
export function credentialOf(d: Doctor): { label: string; items: string[]; total: number } {
  if (d.societies.length > 0) {
    return { label: '학회활동', items: d.societies.slice(0, 2), total: d.societies.length };
  }
  /* ⚠️ '수료' 로 끝나는 줄만 고른다 — 학위·재직 이력을 '수료 과정' 이라 부를 수는 없다. */
  const done = d.career.filter((c) => c.endsWith('수료'));
  return { label: '수료 과정', items: done.slice(0, 2), total: done.length };
}

