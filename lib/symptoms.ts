/**
 * 증상으로 찾기 — 이 사이트의 AEO 핵심 자산.
 *
 * ★ 왜 이 축을 따로 두는가
 *   환자는 병명을 모른다. "치주염" 이라고 검색하는 사람보다 "양치할 때 피가 나요" 라고
 *   묻는 사람이 압도적으로 많고, ChatGPT·Gemini 에 던지는 질문은 거의 전부 후자 형태다.
 *   진료과목 페이지만 있으면 이 질문들을 통째로 놓친다. 그래서 증상을 **입구**로 두고
 *   원인 → 확인 방법 → 치료로 이어지는 경로를 만든다.
 *
 * ★ 문서 구조가 곧 인용 가능성이다
 *   `answer` 는 질문에 대한 즉답이며 2~3문장 안에서 끝난다. AI 는 이 단락을 그대로 인용한다.
 *   원인 후보를 나열할 때도 "가능성이 있다" 를 유지하고 진단으로 단정하지 않는다 —
 *   웹페이지가 환자를 진단할 수는 없고, 단정하면 의료법상 문제가 된다.
 *
 * ★ `urgent` 는 안전장치다
 *   응급 신호를 적어 두지 않으면, 당장 병원에 가야 할 사람이 페이지를 읽고 안심해 버린다.
 *   모든 증상 항목에 반드시 채운다.
 */

export interface Symptom {
  slug: string;
  /** 환자가 말하는 그대로. 검색 질의와 일치시킨다. */
  title: string;
  /** 목록 카드용 짧은 표현. */
  short: string;
  /** 즉답 — 2~3문장. AI 인용 대상. */
  answer: string;
  /** 원인 후보. 단정하지 않는다. */
  causes: Array<{ name: string; detail: string }>;
  /** 내원 전 스스로 해볼 수 있는 것. 치료를 대신하지 않는 범위에서만. */
  selfCare: string[];
  /** 바로 진료가 필요한 신호. 반드시 채운다. */
  urgent: string[];
  /** 연결되는 진료과목 slug. */
  relatedTreatments: string[];
  /**
   * 본문 삽화. **선택**이다 — 없으면 그냥 렌더하지 않는다.
   *
   * ★ 왜 사진이 아니라 삽화인가
   *   증상 페이지에 실제 환자 사진은 쓸 수 없고(초상·의료광고), 시술 장면은 겁을 준다.
   *   AI 로 만든 정서 삽화는 '이 글이 누구 이야기인지' 만 전달하는 역할이다.
   * ⚠️ 진단 근거로 읽히면 안 된다 — 구강 내 사진·엑스레이·기구는 넣지 않는다.
   *   alt 는 화면에 안 보이는 사람에게 '분위기' 가 아니라 '무엇이 찍혔는지' 를 준다.
   */
  image?: { src: string; alt: string };
}

